_metrics_cache: dict = {"period": "", "ts": 0.0, "data": []}
_METRICS_CACHE_TTL = 30.0  # seconds


@router.get("/metrics")
async def get_system_metrics(
    period: str = "1h",
    session: AsyncSession = Depends(get_session),
):
    """System metrics for dashboard charts.

    period: 15m, 1h, 3h, 6h, 12h, 1d, 3d
    """
    import time
    from datetime import datetime, timedelta, timezone
    from app.models import SystemMetric

    # Simple in-memory cache — avoids repeated DB queries from multiple clients
    now = time.monotonic()
    if _metrics_cache["period"] == period and (now - _metrics_cache["ts"]) < _METRICS_CACHE_TTL:
        return _metrics_cache["data"]

    multipliers = {
        "15m": timedelta(minutes=15),
        "1h": timedelta(hours=1),
        "3h": timedelta(hours=3),
        "6h": timedelta(hours=6),
        "12h": timedelta(hours=12),
        "1d": timedelta(days=1),
        "3d": timedelta(days=3),
    }
    delta = multipliers.get(period, timedelta(hours=1))
    since = datetime.now(timezone.utc) - delta

    rows = (await session.exec(
        select(SystemMetric)
        .where(SystemMetric.ts >= since)
        .order_by(SystemMetric.ts)
    )).all()

    # Downsample to at most ~300 points — SVG charts choke on thousands of
    # path points (Firefox STATUS_BREAKPOINT on re-render).
    _MAX_POINTS = 300
    if len(rows) > _MAX_POINTS:
        step = len(rows) // _MAX_POINTS + 1
        rows = rows[::step]

    result = [
        {
            "ts": r.ts.strftime("%Y-%m-%dT%H:%M:%SZ") if r.ts else None,
            "cpu": r.cpu_percent,
            "ram_used": r.ram_used_mb,
            "ram_total": r.ram_total_mb,
            "disk_used": r.disk_used_gb,
            "disk_total": r.disk_total_gb,
            "net_sent": r.net_sent_bytes,
            "net_recv": r.net_recv_bytes,
        }
        for r in rows
    ]

    _metrics_cache["period"] = period
    _metrics_cache["ts"] = now
    _metrics_cache["data"] = result
    return result


@router.patch("/settings", status_code=204)
async def update_settings(body: SettingsUpdate, session: AsyncSession = Depends(get_session)):
    patches = body.model_dump(exclude_unset=True)

    # LAN proxy auth invariant — when the user enables auth, both
    # username and password must be non-empty. Validate against the
    # *post-merge* state: if the patch flips `_enabled=true` but
    # doesn't ship creds, fall back to the existing DB values; if
    # those are also empty, reject with 400 (rather than letting
    # config_gen blow up on the next start_proxy call with a
    # confusing ValueError).
    if patches.get("lan_proxy_auth_enabled") is True:
        existing = {r.key: r.value for r in (await session.exec(select(DBSettings))).all()}
        new_user = (
            patches.get("lan_proxy_auth_user")
            if patches.get("lan_proxy_auth_user") is not None
            else existing.get("lan_proxy_auth_user", "")
        )
        new_pass = (
            patches.get("lan_proxy_auth_pass")
            if patches.get("lan_proxy_auth_pass") is not None
            else existing.get("lan_proxy_auth_pass", "")
        )
        if not (new_user or "").strip() or not new_pass:
            raise HTTPException(
                status_code=400,
                detail=(
                    "LAN proxy auth requires both `lan_proxy_auth_user` "
                    "and `lan_proxy_auth_pass` to be non-empty when "
                    "`lan_proxy_auth_enabled=true`."
                ),
            )

    # Snapshot `inbound_mode` BEFORE the patch so we can roll back if
    # the new value generates an invalid xray config. Without this, the
    # PATCH would persist e.g. `inbound_mode=tun` even though xray
    # rejects the resulting config — the UI then shows "TUN" selected
    # but the runtime keeps the old mode. See backlog item 1 in
    # notes.md ("TUN/Both silently bricks proxy"). The snapshot is
    # cheap: a single Settings row read.
    # Router mode needs a WAN and a LAN. Refuse it on hardware that has only
    # one physical NIC — the UI hides the option there, but the API is the
    # real gate: accepting it would leave a setting the dataplane can never
    # honour, and (once phases 1-2 land) could take the box off the network.
    if patches.get("operating_mode") == "router":
        from app.core.network_config import list_interfaces
        nics = list_interfaces()
        if len(nics) < 2:
            raise HTTPException(
                400,
                f"Router mode needs at least 2 physical network interfaces; "
                f"this box has {len(nics)}"
                + (f" ({', '.join(n['name'] for n in nics)})" if nics else "")
                + ". Keep 'gateway' mode: devices point their gateway at PiTun "
                  "and your existing router keeps doing DHCP and NAT.",
            )
    if patches.get("operating_mode") not in (None, "gateway", "router"):
        raise HTTPException(400, "operating_mode must be 'gateway' or 'router'")

    # Port roles. Validated whenever either role is being set, and again as a
    # completeness check when router mode is switched on — a router with no
    # WAN, or with one port doing both jobs, is not a configuration we should
    # ever persist and then try to apply.
    if any(k in patches for k in ("wan_interface", "lan_interface", "operating_mode")):
        from app.core.network_config import list_interfaces, wifi_capabilities

        async def _current(key: str) -> str:
            row = (await session.exec(
                select(DBSettings).where(DBSettings.key == key)
            )).first()
            return row.value if row else ""

        wan = patches.get("wan_interface")
        lan = patches.get("lan_interface")
        wan = await _current("wan_interface") if wan is None else wan
        lan = await _current("lan_interface") if lan is None else lan
        mode = patches.get("operating_mode")
        if mode is None:
            mode = await _current("operating_mode") or "gateway"

        if wan or lan:
            names = {i["name"] for i in list_interfaces()}
            for role, value in (("wan_interface", wan), ("lan_interface", lan)):
                if value and value not in names:
                    raise HTTPException(
                        400,
                        f"{role} '{value}' is not a physical interface on this box "
                        f"({', '.join(sorted(names)) or 'none detected'})",
                    )
            if wan and lan and wan == lan:
                raise HTTPException(
                    400,
                    f"WAN and LAN cannot be the same port ('{wan}') — router mode "
                    "needs one port facing the ISP and another facing the network.",
                )
            # Serving the LAN over WiFi means running an access point, which
            # only some radios can do. Catch it here rather than at hostapd
            # start, which happens after the working setup is torn down.
            if lan:
                cap = wifi_capabilities(lan)
                if cap["wireless"] and cap["ap_capable"] is False:
                    raise HTTPException(
                        400,
                        f"'{lan}' is a client-only wireless adapter — it cannot serve "
                        "the LAN. Use a wired port for LAN, or a WiFi adapter that "
                        "supports AP mode.",
                    )
                if cap["wireless"] and cap["ap_capable"] is None:
                    raise HTTPException(
                        400,
                        f"Cannot confirm '{lan}' supports AP mode: {cap['detail']}. "
                        "Resolve that before assigning it as the LAN port.",
                    )

        if mode == "router" and (not wan or not lan):
            missing = " and ".join(
                r for r, v in (("a WAN port", wan), ("a LAN port", lan)) if not v
            )
            raise HTTPException(
                400, f"Router mode needs {missing} assigned before it can be enabled.",
            )

    inbound_mode_was = None
    if "inbound_mode" in patches and patches["inbound_mode"] is not None:
        existing_row = (await session.exec(
            select(DBSettings).where(DBSettings.key == "inbound_mode")
        )).first()
        inbound_mode_was = existing_row.value if existing_row else "tproxy"

    for key, value in patches.items():
        if value is None:
            continue
        if key == "failover_node_ids":
            await _set_setting(session, key, json.dumps(value))
        elif isinstance(value, bool):
            await _set_setting(session, key, str(value).lower())
        elif isinstance(value, int):
            await _set_setting(session, key, str(value))
        else:
            await _set_setting(session, key, str(value))
    await session.commit()

    # Post-commit pre-flight for inbound_mode changes. We commit first
    # (so the helper that loads settings_map sees the new value), then
    # generate + validate. On failure, rewrite the row back to its old
    # value and raise 400 — the UI's mutation will surface the error
    # and stay on the previous mode. xray-side state is untouched
    # because we never restarted it (writing config.json is harmless
    # if xray isn't reloaded).
    if (
        inbound_mode_was is not None
        and str(patches.get("inbound_mode")) != inbound_mode_was
    ):
        from app.core.config_gen import (
            generate_config, write_config,
            _diagnose_empty_stderr, _xray_version,
        )
        from pathlib import Path
        from app.config import settings as app_settings
        import asyncio

        # Generate a candidate config under the new mode. We can't
        # simply call _regenerate_and_write because that path triggers
        # self-healing of geo rules — orthogonal to mode validation
        # and would mask the real "this mode is unsupported" error.
        settings_map = await _load_settings_map(session)
        active_id_str = settings_map.get("active_node_id", "")
        active_node = None
        if active_id_str:
            try:
                active_node = await session.get(Node, int(active_id_str))
            except ValueError:
                pass
        all_nodes = list((await session.exec(select(Node).where(Node.enabled == True))).all())
        rules = list((await session.exec(select(RoutingRule).where(RoutingRule.enabled == True))).all())
        dns_rules = list((await session.exec(select(DNSRule).where(DNSRule.enabled == True))).all())
        balancer_groups = list((await session.exec(select(BalancerGroup))).all())
        from app.core.config_gen import collect_routing_set_context
        routing_sets, device_set_macs = await collect_routing_set_context(session)
        candidate = generate_config(
            active_node, all_nodes, rules,
            settings_map.get("mode", "rules"),
            settings_map, dns_rules, balancer_groups,
            routing_sets=routing_sets, device_set_macs=device_set_macs,
        )

        # In-process pre-flight: write to a tmp path and run xray -test
        # there. NOT the real config.json — we don't want a successful
        # write that gets overridden on rollback.
        ok = True
        diag = "unknown error"
        try:
            if Path(app_settings.xray_binary).exists():
                tmp_path = f"{app_settings.xray_config_path}.candidate"
                import json as _json
                Path(tmp_path).parent.mkdir(parents=True, exist_ok=True)
                with open(tmp_path, "w") as f:
                    _json.dump(candidate, f, indent=2)
                proc = await asyncio.create_subprocess_exec(
                    app_settings.xray_binary, "run", "-test", "-config", tmp_path,
                    stdout=asyncio.subprocess.PIPE,
                    stderr=asyncio.subprocess.PIPE,
                )
                _, stderr = await asyncio.wait_for(proc.communicate(), timeout=10)
                Path(tmp_path).unlink(missing_ok=True)
                if proc.returncode != 0:
                    ok = False
                    stderr_text = stderr.decode(errors="replace").strip()
                    if not stderr_text:
                        ver = await _xray_version()
                        diag = _diagnose_empty_stderr(
                            xray_version=ver,
                            inbound_mode=patches.get("inbound_mode"),
                            config=candidate,
                        )
                    else:
                        diag = stderr_text.splitlines()[-1][:300]
        except Exception as exc:  # noqa: BLE001
            # Pre-flight failure due to binary missing / hung etc is
            # advisory only — let the value through. Same policy as
            # `write_config` (advisory pre-flight).
            import logging
            logging.getLogger(__name__).debug(
                "inbound_mode pre-flight skipped: %s", exc,
            )

        if not ok:
            # Roll back the inbound_mode row + commit so DB reflects
            # reality. Other patched keys stay applied (they didn't
            # cause the failure).
            await _set_setting(session, "inbound_mode", inbound_mode_was)
            await session.commit()
            raise HTTPException(
                status_code=400,
                detail=(
                    f"Inbound mode '{patches['inbound_mode']}' produces an "
                    f"invalid xray config — change reverted. "
                    f"Details: {diag}"
                ),
            )

    # Apply IPv6 toggle via bind-mounted host /proc/sys
    if "disable_ipv6" in patches:
        val = "1" if patches["disable_ipv6"] else "0"
        for path in ("net/ipv6/conf/all/disable_ipv6", "net/ipv6/conf/default/disable_ipv6"):
            try:
                with open(f"{_HOST_PROC_SYS}/{path}", "w") as f:
                    f.write(val)
            except Exception:
                pass

    # Apply DNS over TCP toggle via bind-mounted host /etc/resolv.conf
    if "dns_over_tcp" in patches:
        try:
            with open(_HOST_RESOLV) as f:
                lines = [l for l in f.read().splitlines() if "use-vc" not in l]
            if patches["dns_over_tcp"]:
                lines.append("options use-vc")
            with open(_HOST_RESOLV, "w") as f:
                f.write("\n".join(lines) + "\n")
        except Exception:
            pass

    # Apply host fallback DNS additively (NM / systemd-resolved /
    # resolv.conf depending on what the host runs). Non-destructive —
    # keeps the DHCP/router DNS primary, appends our fallbacks.
    if "host_fallback_dns" in patches:
        try:
            from app.core.network_apply import apply_host_fallback_dns
            raw = str(patches["host_fallback_dns"] or "")
            servers = [s.strip() for s in raw.split(",") if s.strip()]
            apply_host_fallback_dns(servers)
        except Exception as exc:
            logger.warning("host_fallback_dns apply failed: %s", exc)

    # LAN proxy auth changes affect the running xray config (SOCKS +
    # HTTP inbounds get `accounts` injected/removed). Reload xray on
    # the fly so the user sees the change without going to /restart —
    # they toggle this from the Dashboard inline UI and expect
    # immediate effect. Skipped silently if xray isn't running.
    lan_auth_keys = {
        "lan_proxy_auth_enabled",
        "lan_proxy_auth_user",
        "lan_proxy_auth_pass",
    }
    if patches.keys() & lan_auth_keys:
        try:
            from app.core.xray import xray_manager
            if xray_manager.is_running:
                await _regenerate_and_write(session)
                await xray_manager.reload()
        except Exception as exc:
            # Log and continue — the next manual /start will pick up
            # the new creds anyway. Don't 500 the PATCH because reload
            # races with another lifecycle event.
            import logging
            logging.getLogger(__name__).warning(
                "LAN proxy auth applied but xray reload failed: %s", exc,
            )


# ── Internal helpers ──────────────────────────────────────────────────────────

async def _regenerate_and_write(session: AsyncSession, *, _self_heal_attempts: int = 0) -> None:
    """Re-generate xray config from current DB state and write it to
    disk, with pre-flight `xray run -test` validation.

    Self-healing (since v1.2.7): if validation fails because a routing
    rule references a geosite/geoip tag absent from the loaded `.dat`,
    we auto-disable the offending rules, append them to
    `Settings.auto_disabled_rules` (JSON list — surfaced by the
    frontend as a banner above the Routing table), and recursively
    retry the write with the smaller ruleset. Bounded to 5 attempts
    so a pathological `.dat` mismatch can't infinite-loop.
    """
    from app.core.config_gen import generate_config, write_config, collect_routing_set_context

    settings_map = await _load_settings_map(session)
    mode = settings_map.get("mode", "rules")
    active_id_str = settings_map.get("active_node_id", "")
    active_node = None
    if active_id_str:
        try:
            active_node = await session.get(Node, int(active_id_str))
        except ValueError:
            pass

    all_nodes = list((await session.exec(select(Node).where(Node.enabled == True))).all())
    rules = list((await session.exec(select(RoutingRule).where(RoutingRule.enabled == True))).all())
    dns_rules = list((await session.exec(select(DNSRule).where(DNSRule.enabled == True))).all())
    balancer_groups = list((await session.exec(select(BalancerGroup))).all())
    routing_sets, device_set_macs = await collect_routing_set_context(session)
    from app.models import NodeCircle
    from app.core.config_gen import resolve_active_circle
    circles = list((await session.exec(select(NodeCircle))).all())
    active_circle_id, active_circle_node_ids = resolve_active_circle(
        circles, active_node.id if active_node else None
    )
    config = generate_config(
        active_node, all_nodes, rules, mode, settings_map, dns_rules, balancer_groups,
        routing_sets=routing_sets, device_set_macs=device_set_macs,
        active_circle_id=active_circle_id, active_circle_node_ids=active_circle_node_ids,
    )

    # On retry passes we skip pre-flight to avoid recursive cost — the
    # outer attempt's pre-flight already proved which rules are bad,
    # and disabling them can't introduce new validation issues. Last
    # write of a healing chain re-runs with validate=True so the
    # success path clears `last_xray_validation_error`.
    heal_target = await write_config(config, validate=True)

    # Strict shape check — `heal_target` should be either None or a
    # 2-tuple of (str, str). Anything else (e.g. a stray mock or a
    # future schema change) is treated as None to avoid running the
    # self-heal path on garbage. Pre-1.2.7 callers + tests using
    # `AsyncMock(write_config)` without `return_value=None` would
    # otherwise see a MagicMock here and attempt recursion.
    if not (
        isinstance(heal_target, tuple)
        and len(heal_target) == 2
        and isinstance(heal_target[0], str)
        and isinstance(heal_target[1], str)
    ):
        return

    if _self_heal_attempts >= 5:
        # Give up: keep the current `last_xray_validation_error` set so
        # the admin still sees the underlying problem; don't loop.
        logger.error(
            "Self-heal exhausted (5 attempts) — leaving last_xray_validation_error in place"
        )
        return

    kind, tag = heal_target
    disabled_now = await _self_heal_disable_geo_rules(session, kind, tag)
    if not disabled_now:
        # No rules referenced the offending tag despite xray reporting
        # one — likely the rule was re-enabled or the parser disagrees
        # with xray. Stop trying to heal.
        logger.warning(
            "Self-heal: xray rejected %s:%s but no enabled rule references it; "
            "leaving config + error untouched", kind, tag,
        )
        return

    logger.info(
        "Self-heal disabled %d rule(s) referencing %s:%s — retrying config write (attempt %d)",
        len(disabled_now), kind, tag, _self_heal_attempts + 1,
    )
    await _regenerate_and_write(session, _self_heal_attempts=_self_heal_attempts + 1)


async def _self_heal_disable_geo_rules(
    session: AsyncSession, kind: str, tag: str
) -> List[int]:
    """Disable every enabled `RoutingRule` that references the given
    geosite/geoip tag, and append a record to the
    `Settings.auto_disabled_rules` JSON list. Returns the list of
    rule ids actually flipped.
    """
    from app.models import RoutingRule
    import json as _json
    from datetime import datetime as _dt, timezone as _tz

    rules = (await session.exec(
        select(RoutingRule).where(RoutingRule.enabled == True)
    )).all()

    affected: List[RoutingRule] = []
    needle_lc = tag.lower()
    for r in rules:
        rt = (r.rule_type or "").lower()
        mv = (r.match_value or "").lower()
        if rt == kind:
            parts = [p.strip() for p in mv.split(",") if p.strip()]
            if needle_lc in parts:
                affected.append(r)
        elif rt == "domain":
            # Inline `geosite:X` / `geoip:X` inside a domain-mode rule.
            inline = f"{kind}:{needle_lc}"
            parts = [p.strip() for p in mv.split(",") if p.strip()]
            if inline in parts:
                affected.append(r)

    if not affected:
        return []

    # Snapshot every attribute we'll need after commit() into plain
    # tuples — `session.commit()` expires SQLModel instance attrs by
    # default, and any subsequent attribute access triggers a lazy
    # reload that fails outside an awaitable context with
    # `MissingGreenlet` ("can't call await_only() here"). The
    # snapshot lets us read the values back without re-touching the
    # ORM after commit.
    snapshots = [
        (r.id, r.name, r.rule_type, r.match_value)
        for r in affected
    ]

    for r in affected:
        r.enabled = False
        session.add(r)

    # Append (rule_id, name, kind, tag, disabled_at) entries to the
    # settings key so the UI banner can show what happened. The list
    # acts as an inbox the admin clears explicitly via the banner's
    # "Re-enable" / "Delete" / "Dismiss" actions.
    row = (await session.exec(
        select(DBSettings).where(DBSettings.key == "auto_disabled_rules")
    )).first()
    try:
        existing = _json.loads(row.value) if row and row.value else []
        if not isinstance(existing, list):
            existing = []
    except Exception:
        existing = []

    now_iso = _dt.now(_tz.utc).isoformat(timespec="seconds")
    for rule_id, rule_name, rule_type, match_value in snapshots:
        existing.append({
            "rule_id": rule_id,
            "name": rule_name,
            "rule_type": rule_type,
            "match_value": match_value,
            "missing_kind": kind,
            "missing_tag": tag,
            "disabled_at": now_iso,
        })

    payload = _json.dumps(existing)
    if row:
        row.value = payload
        session.add(row)
    else:
        session.add(DBSettings(key="auto_disabled_rules", value=payload))

    await session.commit()
    # IDs returned from the pre-commit snapshot — `affected[i].id`
    # would re-fetch from the DB after the expire-on-commit.
    return [s[0] for s in snapshots]


async def _load_settings_map(session: AsyncSession) -> dict:
    rows = (await session.exec(select(DBSettings))).all()
    return {row.key: row.value for row in rows}


def _collect_bypass_macs(rules: List[RoutingRule]) -> List[str]:
    macs = []
    for rule in rules:
        if rule.rule_type == "mac" and rule.action == "direct":
            macs.extend(v.strip() for v in rule.match_value.split(","))
    return macs


