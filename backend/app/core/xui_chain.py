def _no_expire_on_commit(session: AsyncSession) -> None:
    """Disable expire-on-commit for the rest of this session's life.

    SQLAlchemy's default is to mark every attached instance as expired
    after `commit()`, so the next attribute access reloads via the DB.
    In a sync session that's transparent; in an AsyncSession the
    reload tries to dispatch IO through the sync greenlet and
    crashes with `MissingGreenlet: can't call await_only() here`.

    Every orchestrate_* function below commits multiple times and
    keeps reading from the same ORM instances afterwards
    (`exit_xs.api_token`, `exit_srv.host`, `channel.exit_port`, …).
    Snapshotting each field by hand turned out to be brittle — new
    fields kept getting added and the bug re-surfaced — so we just
    flip the session-level flag once at entry and read freely.

    Safe because the orchestrators are the sole writer to the
    XuiServer / Server / ChainChannel rows they touch during the
    call; nothing else races to overwrite them mid-flight.
    """
    try:
        session.sync_session.expire_on_commit = False
    except Exception:  # noqa: BLE001 — be defensive; SA internals may rename
        pass


async def _ufw_chain_ports(
    server: Server, ports: List[int], *, action: str,
) -> None:
    """Open / close TCP ports on the VPS via SSH + UFW.

    UFW on a default-deny VPS will silently drop SYNs to chain inbound
    ports until we explicitly allow them. The reference setup-eu.sh /
    setup-relay.sh do this inline because they run on the VPS itself;
    PiTun creates inbounds through the panel API, so the UFW step has
    to happen separately.

    `action` is "allow" or "delete-allow"; best-effort — a failure
    here is logged but doesn't abort the chain operation. The user
    can always open / close the port manually.
    """
    if not ports:
        return
    cmd = "set -e\n"
    for p in ports:
        if action == "allow":
            cmd += f"ufw allow {int(p)}/tcp || true\n"
        elif action == "delete-allow":
            cmd += f"ufw delete allow {int(p)}/tcp || true\n"
    cmd += "ufw reload || true\n"
    try:
        res = await exec_remote_script(
            host=server.host, port=server.port or 22,
            username=server.user or "root",
            password=server.password,
            private_key=server.private_key,
            script_content=cmd,
            timeout=30.0,
        )
        if not res.ok:
            logger.warning(
                "ufw %s on %s ports=%s: exit=%s err=%s",
                action, server.host, ports, res.exit_code, res.error,
            )
    except Exception as exc:  # noqa: BLE001
        logger.warning(
            "ufw %s on %s ports=%s raised: %s",
            action, server.host, ports, exc,
        )


async def _clear_xray_template_via_ssh(server: Server) -> None:
    """Hard-clear `xrayTemplateConfig` on the panel + restart x-ui.

    Why over SSH instead of the panel API:
      The `/panel/xray/update` endpoint only knows how to set
      `xraySetting` to a value. Pushing an empty string stores `''`
      in the settings table but the panel keeps using the previously
      assembled `bin/config.json` — so the chain outbound + routing
      rule survive a subsequent restart and any unmatched inbound
      traffic ends up falling through to `* -> blocked`. Only a hard
      `DELETE FROM settings WHERE key = 'xrayTemplateConfig'` + an
      explicit `x-ui restart` causes the panel to rebuild routing
      from defaults (api → api, geoip:private → blocked,
      bittorrent → blocked) so standalone inbounds get the implicit
      catch-all `direct` outbound xray picks when no rule matches.

    Called on the LAST chain-delete for a relay panel so the operator
    can keep adding plain inbounds without their traffic blackholing.
    Best-effort: failure is logged but doesn't unwind the delete.
    """
    cmd = (
        "set -e\n"
        # The panel can install its sqlite in either location depending
        # on how old the installer was; try both.
        "for db in /etc/x-ui/x-ui.db /usr/local/x-ui/db/x-ui.db; do\n"
        "  if [ -f \"$db\" ]; then\n"
        "    sqlite3 \"$db\" \"DELETE FROM settings WHERE key='xrayTemplateConfig';\"\n"
        "  fi\n"
        "done\n"
        "x-ui restart >/dev/null 2>&1 || systemctl restart x-ui >/dev/null 2>&1 || true\n"
    )
    try:
        # `x-ui restart` can take 30-45s on slow VPSes (Go's runtime
        # init + xray's startup + the panel writing a fresh
        # bin/config.json from sqlite). Give it real headroom; the
        # operator-visible side of the chain delete already returned
        # by the time this runs, so a long wait here doesn't block UX.
        res = await exec_remote_script(
            host=server.host, port=server.port or 22,
            username=server.user or "root",
            password=server.password,
            private_key=server.private_key,
            script_content=cmd,
            timeout=90.0,
        )
        if not res.ok:
            logger.warning(
                "clear xrayTemplateConfig on %s: exit=%s err=%s",
                server.host, res.exit_code, res.error,
            )
        else:
            logger.info(
                "Last chain removed from relay %s — xrayTemplateConfig "
                "deleted + x-ui restarted (panel auto-routing restored).",
                server.host,
            )
    except Exception as exc:  # noqa: BLE001
        logger.warning(
            "clear xrayTemplateConfig on %s raised: %s", server.host, exc,
        )


# ── Input shapes (used by the API layer + tests) ────────────────────────────


@dataclass
class ChannelDraft:
    """User-supplied channel parameters for a chain create request.

    Everything except `name` has a defaulted-or-generated path:
      * `exit_port` / `relay_port` — if 0/empty, the orchestrator
        picks free random ports in well-separated ranges (10000-19999
        for exit, 20000-29999 for relay) so collisions across channels
        within the same chain are vanishingly rare. The orchestrator
        also probes the panel's existing inbound list for the chosen
        port and re-rolls on conflict.
      * `exit_xhttp_path` — defaults to `/api/v1/<name>`.
      * `client_sni` — must be supplied by the user; this is the
        whole point of having multiple channels (different SNI =
        different DPI cover).
      * `relay_inbound_remark` / `exit_inbound_remark` — defaults
        derived from `name`.
    """

    name: str               # alnum + `-` + `_`, max 64 chars
    client_sni: str         # the SNI DPI sees on client→relay
    exit_port: int = 0      # 0 = auto-pick
    relay_port: int = 0     # 0 = auto-pick
    exit_xhttp_path: str = ""  # empty = `/api/v1/<name>`
    relay_remark: str = ""  # empty = `VPN-<name.upper()>`
    exit_remark: str = ""   # empty = `<name.upper()>-Exit`


@dataclass
class ChainCreateDraft:
    """Top-level chain create request — what the API layer passes
    into `orchestrate_create`."""

    name: str
    exit_xui_server_id: int
    relay_xui_server_id: int
    exit_sni: str
    channels: List[ChannelDraft]


# ── Tag conventions ─────────────────────────────────────────────────────────


def _exit_tag(chain_id: int, channel_name: str) -> str:
    """The xray inbound `tag` for an exit-side inbound.

    Format `chain-<id>-<name>-exit`. Used both as the inbound's own
    tag (so /sync can find it again after a panel reboot) and as
    the relay outbound's name (so the routing rule on the relay
    references it cleanly)."""
    return f"chain-{chain_id}-{channel_name}-exit"


def _relay_tag(chain_id: int, channel_name: str) -> str:
    return f"chain-{chain_id}-{channel_name}-relay"


# ── Build helpers — keep panel-payload generation pure-functional so ───────
# the orchestrator can be unit-tested without an httpx pool.


def _sniff() -> Dict[str, Any]:
    """Standard sniffing block for both sides. Copy from xui_presets's
    helper but inlined here so the chain layer doesn't depend on the
    preset module (presets are user-facing single-server inbounds —
    chains build their own wire shapes)."""
    return {
        "enabled": True,
        "destOverride": ["http", "tls", "quic", "fakedns"],
        "metadataOnly": False,
        "routeOnly": False,
    }


def _build_exit_inbound_payload(
    *,
    chain_id: int,
    channel: ChannelDraft,
    bootstrap_uuid: str,
    exit_sni: str,
    private_key: str,
    public_key: str,
    short_id: str,
    bootstrap_email: str,
) -> Dict[str, Any]:
    """xhttp + Reality inbound on the exit panel.

    The `clients` array carries ONE bootstrap UUID — the relay's
    outbound will use this to dial in. ChainClient creation later
    appends more clients to this same inbound via addClient, but
    those are for the relay→exit hop on a per-user basis. Wait, no:
    in the user's reference setup-relay.sh the relay-side outbound
    has ONE bootstrap UUID baked into the xrayTemplateConfig, and
    that UUID is shared across all relay-side clients (the routing
    layer doesn't care which user it is — the per-user identity
    is on the client→relay hop). So we ship one bootstrap UUID and
    leave it at that.
    """
    settings = {
        "clients": [
            {
                "id": bootstrap_uuid,
                "flow": "",
                "email": bootstrap_email,
                "limitIp": 0, "totalGB": 0, "expiryTime": 0,
                "enable": True, "tgId": "", "subId": "",
            },
        ],
        "decryption": "none",
        "fallbacks": [],
    }
    stream = {
        "network": "xhttp",
        "security": "reality",
        "realitySettings": {
            "show": False, "xver": 0,
            "dest": f"{exit_sni}:443",
            "serverNames": [exit_sni],
            "privateKey": private_key,
            "minClient": "", "maxClient": "", "maxTimediff": 0,
            "shortIds": [short_id],
            "settings": {
                "publicKey": public_key,
                "fingerprint": "chrome",
                "serverName": "",
                "spiderX": "/",
            },
        },
        "xhttpSettings": {
            "path": channel.exit_xhttp_path or f"/api/v1/{channel.name}",
            "mode": "packet-up",
        },
    }
    return {
        "up": 0, "down": 0, "total": 0,
        "remark": channel.exit_remark or f"{channel.name.upper()}-Exit",
        "enable": True, "expiryTime": 0,
        "listen": "", "port": channel.exit_port,
        "protocol": "vless",
        "tag": _exit_tag(chain_id, channel.name),
        "settings": settings,
        "streamSettings": stream,
        "sniffing": _sniff(),
    }


