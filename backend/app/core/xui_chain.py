def _api_base_url(xs: XuiServer, srv: Server) -> str:
    """Mirror of the helper in api/xui.py. Duplicated to avoid an
    import cycle (xui_chain → api/xui → models).

    Bare mode → plain HTTP on a random high port (panel uses no cert).
    xui-pro mode → HTTPS via LE cert wired into the panel's
    webCertFile / webCertKey settings by setup-xui-server.sh's
    section 4b.
    """
    if xs.mode == "xui-pro" and xs.domain:
        return f"https://{xs.domain}:{xs.panel_port}{xs.panel_basepath}"
    return f"http://{srv.host}:{xs.panel_port}{xs.panel_basepath}"


def _wrap_settings_json(payload: Dict[str, Any]) -> Dict[str, Any]:
    """3x-ui stores `settings` / `streamSettings` / `sniffing` as
    JSON-in-JSON: the outer body has them as strings, not nested
    objects. Same quirk as add_client (see xui_api.py)."""
    wire = dict(payload)
    for key in ("settings", "streamSettings", "sniffing"):
        if key in wire and not isinstance(wire[key], str):
            wire[key] = json.dumps(wire[key])
    return wire


async def _push_xray_template(
    *,
    relay_client: XuiClient,
    template: Dict[str, Any],
) -> None:
    """Replace the relay's xray template via /panel/xray/update.

    3x-ui v3.0.1 dropped `xrayTemplateConfig` from /panel/setting/all
    — xray config now lives in its own XraySettingController under
    /panel/xray/*. We fetch the current template (just to preserve
    `outboundTestUrl`), then push the new one. Cookie+CSRF auth —
    requires the relay XuiClient to be built with `panel_user` +
    `panel_pass`.
    """
    current = await relay_client.get_xray_setting()
    test_url = current.get("outboundTestUrl") if isinstance(current, dict) else None
    await relay_client.push_xray_setting(template, test_url)


async def _restart_xray(relay_client: XuiClient) -> None:
    """Restart Xray on the relay so it picks up the new template."""
    await relay_client.restart_xray()


async def orchestrate_create(
    *,
    draft: ChainCreateDraft,
    session: AsyncSession,
) -> ProxyChain:
    """Create a chain end-to-end.

    Steps:
      1. Validate the panels exist + load their parent Server rows.
      2. Allocate ports (random, conflict-checked against each panel's
         live inbound list).
      3. Create the ProxyChain row + channel drafts in DB (status=
         pending) — gives us a `chain_id` to use in tags.
      4. For each channel:
         a. getNewUUID + getNewX25519Cert × 2 (one for exit, one for
            relay; shortIds are local random).
         b. POST add_inbound on the exit panel.
         c. POST add_inbound on the relay panel.
         d. Update the ChainChannel row with remote_ids + Reality
            material.
      5. Build the relay xrayTemplateConfig from the now-populated
         channels + push to the relay panel.
      6. Restart Xray on the relay.
      7. Flip chain.status = 'deployed'.

    Rollback: any exception in steps 4-6 triggers `_rollback_inbounds`
    which deletes every panel-side inbound we got a remote_id for,
    then re-raises with a wrapped error message. The DB rows are
    flagged status='failed' so the UI can show the failure + offer
    delete/retry — they're NOT auto-removed because partial state
    on the panels may still need manual cleanup the user wants to
    see.
    """
    _no_expire_on_commit(session)
    # Step 1 — resolve panels.
    exit_xs = await session.get(XuiServer, draft.exit_xui_server_id)
    relay_xs = await session.get(XuiServer, draft.relay_xui_server_id)
    if exit_xs is None or relay_xs is None:
        raise ValueError("exit_xui_server_id or relay_xui_server_id not found")
    if exit_xs.id == relay_xs.id:
        raise ValueError("exit and relay must be different panels")

    exit_srv = await session.get(Server, exit_xs.server_id)
    relay_srv = await session.get(Server, relay_xs.server_id)
    if exit_srv is None or relay_srv is None:
        raise RuntimeError("Server row missing for one of the panels")

    # Channel-name uniqueness check (DB will enforce via the
    # composite unique constraint anyway, but a clean 400 beats a
    # mid-orchestration IntegrityError).
    seen_names: set[str] = set()
    for ch in draft.channels:
        if ch.name in seen_names:
            raise ValueError(f"Duplicate channel name in draft: {ch.name!r}")
        seen_names.add(ch.name)

    exit_url = _api_base_url(exit_xs, exit_srv)
    relay_url = _api_base_url(relay_xs, relay_srv)

    # Snapshot every ORM attribute we'll need AFTER the step-3 commit
    # below. The commit expires every attached instance, and any
    # subsequent attribute read triggers SQLAlchemy's sync lazy-load
    # callback inside the async session — `MissingGreenlet: can't call
    # await_only() here`. Cache them all here once.
    exit_token = exit_xs.api_token
    relay_token = relay_xs.api_token
    exit_host = exit_srv.host
    relay_host = relay_srv.host  # noqa: F841 — kept for symmetry / future use
    # Cookie+CSRF creds — only the relay needs them (to update
    # xrayTemplateConfig via /panel/setting/update in step 5).
    relay_user = relay_xs.panel_user
    relay_pass = relay_xs.panel_pass

    # Step 2 — port allocation.
    # Probe each panel for ports already in use so we don't collide
    # with hand-added inbounds the operator may have set up.
    async with XuiClient(
        base_url=exit_url, api_token=exit_token, verify_tls=False,
    ) as exit_client:
        exit_existing = await exit_client.list_inbounds()
    async with XuiClient(
        base_url=relay_url, api_token=relay_token, verify_tls=False,
    ) as relay_client:
        relay_existing = await relay_client.list_inbounds()

    exit_used = {int(ib.get("port") or 0) for ib in exit_existing}
    relay_used = {int(ib.get("port") or 0) for ib in relay_existing}
    # xui-pro panels run on a domain → Caddy/nginx/LE-ACME hold
    # ports 80 + 443 outside the panel's own inbound list. Binding
    # an inbound there makes Xray start with "address already in
    # use" and leaves the chain half-broken. Reserve them upfront.
    if exit_xs.mode == "xui-pro":
        exit_used |= {80, 443}
    if relay_xs.mode == "xui-pro":
        relay_used |= {80, 443}

    # Per-draft uniqueness pre-check. Two channels claiming the same
    # port on the same panel side will succeed on the API level (the
    # panel happily takes both into its sqlite) but xray will only
    # bind one of them, leaving the other's Reality keys orphan. The
    # client URL for the orphan channel keeps "connecting" on TCP
    # (xray's other inbound is listening) but Reality handshake
    # silently drops because the keys don't match → speedtest shows
    # "too small (0B)". Catch this UP FRONT instead of letting the
    # operator chase a silent-failure mode after the fact.
    user_exit_ports: Dict[int, str] = {}
    user_relay_ports: Dict[int, str] = {}
    for ch in draft.channels:
        if ch.exit_port:
            if ch.exit_port in user_exit_ports:
                raise ValueError(
                    f"Channels {user_exit_ports[ch.exit_port]!r} and {ch.name!r} "
                    f"both claim exit_port {ch.exit_port} — each channel must "
                    "land on a different port on the exit panel."
                )
            user_exit_ports[ch.exit_port] = ch.name
        if ch.relay_port:
            if ch.relay_port in user_relay_ports:
                raise ValueError(
                    f"Channels {user_relay_ports[ch.relay_port]!r} and {ch.name!r} "
                    f"both claim relay_port {ch.relay_port} — each channel must "
                    "land on a different port on the relay panel."
                )
            user_relay_ports[ch.relay_port] = ch.name

    # Apply user-supplied ports first (so the auto-pick respects them
    # as "already chosen"), then fill gaps.
    auto_exit = set(user_exit_ports.keys())
    auto_relay = set(user_relay_ports.keys())
    for ch in draft.channels:
        if ch.exit_port == 0:
            ch.exit_port = _pick_port(auto_exit, exit_used, 10000, 19999)
        elif ch.exit_port in exit_used:
            why = "reserved by panel HTTPS (Caddy / ACME)" \
                if ch.exit_port in (80, 443) and exit_xs.mode == "xui-pro" \
                else "already in use on exit panel"
            raise ValueError(
                f"Channel {ch.name!r}: exit_port {ch.exit_port} — {why}"
            )
        if ch.relay_port == 0:
            ch.relay_port = _pick_port(auto_relay, relay_used, 20000, 29999)
        elif ch.relay_port in relay_used:
            why = "reserved by panel HTTPS (Caddy / ACME)" \
                if ch.relay_port in (80, 443) and relay_xs.mode == "xui-pro" \
                else "already in use on relay panel"
            raise ValueError(
                f"Channel {ch.name!r}: relay_port {ch.relay_port} — {why}"
            )

    # Step 3 — DB rows. Commit so we have a chain_id to use in tags
    # BEFORE any panel mutation; rollback on failure drops these
    # via session.delete.
    now = datetime.now(timezone.utc)
    chain = ProxyChain(
        name=draft.name,
        exit_xui_server_id=exit_xs.id,
        relay_xui_server_id=relay_xs.id,
        exit_sni=draft.exit_sni,
        status="pending",
        created_at=now,
        updated_at=now,
    )
    session.add(chain)
    await session.flush()  # populates chain.id without commit

    channel_rows: List[ChainChannel] = []
    for order, draft_ch in enumerate(draft.channels):
        row = ChainChannel(
            chain_id=chain.id,
            name=draft_ch.name,
            order=order,
            exit_port=draft_ch.exit_port,
            relay_port=draft_ch.relay_port,
            exit_xhttp_path=draft_ch.exit_xhttp_path or f"/api/v1/{draft_ch.name}",
            client_sni=draft_ch.client_sni,
            relay_inbound_remark=draft_ch.relay_remark or f"VPN-{draft_ch.name.upper()}",
            exit_inbound_remark=draft_ch.exit_remark or f"{draft_ch.name.upper()}-Exit",
            created_at=now,
        )
        session.add(row)
        channel_rows.append(row)
    await session.flush()  # populate row.id for each channel
    await session.commit()
    # commit() above expires every attached ORM instance. The loop in
    # step 4 below reads `ch.name` / `chain.id` / etc., which would
    # otherwise trigger SQLAlchemy's sync lazy-load callback inside
    # the async session — `MissingGreenlet: can't call await_only()`.
    # Refresh them eagerly to repopulate the attribute cache.
    await session.refresh(chain)
    for row in channel_rows:
        await session.refresh(row)

    # Step 4 — panel-side create. Track every (panel, remote_id)
    # pair we successfully add so rollback can undo them.
    created_exit: List[int] = []   # remote_ids on exit panel
    created_relay: List[int] = []  # remote_ids on relay panel

    try:
        async with XuiClient(
            base_url=exit_url, api_token=exit_token, verify_tls=False,
        ) as exit_client, XuiClient(
            base_url=relay_url, api_token=relay_token, verify_tls=False,
            panel_user=relay_user, panel_pass=relay_pass,
        ) as relay_client:

            for ch in channel_rows:
                draft_ch = next(d for d in draft.channels if d.name == ch.name)

                # Per-channel crypto material.
                bootstrap_uuid = await exit_client.get_new_uuid()
                exit_pvk, exit_pbk = await exit_client.get_new_x25519_cert()
                relay_pvk, relay_pbk = await relay_client.get_new_x25519_cert()
                exit_sid = secrets.token_hex(4)
                relay_sid = secrets.token_hex(4)
                bootstrap_email = f"chain-{chain.id}-{ch.name}-boot"

                # 4b. Exit inbound.
                exit_payload = _build_exit_inbound_payload(
                    chain_id=chain.id, channel=draft_ch,
                    bootstrap_uuid=bootstrap_uuid,
                    exit_sni=draft.exit_sni,
                    private_key=exit_pvk, public_key=exit_pbk,
                    short_id=exit_sid,
                    bootstrap_email=bootstrap_email,
                )
                exit_created = await exit_client.add_inbound(
                    _wrap_settings_json(exit_payload),
                )
                exit_id = int(exit_created.get("id") or 0)
                if not exit_id:
                    raise XuiAPIError(
                        "exit add_inbound returned no id",
                        kind="format",
                    )
                created_exit.append(exit_id)

                # 4c. Relay inbound.
                relay_payload = _build_relay_inbound_payload(
                    chain_id=chain.id, channel=draft_ch,
                    bootstrap_uuid=bootstrap_uuid,
                    private_key=relay_pvk, public_key=relay_pbk,
                    short_id=relay_sid,
                    bootstrap_email=bootstrap_email,
                )
                relay_created = await relay_client.add_inbound(
                    _wrap_settings_json(relay_payload),
                )
                relay_id = int(relay_created.get("id") or 0)
                if not relay_id:
                    raise XuiAPIError(
                        "relay add_inbound returned no id",
                        kind="format",
                    )
                created_relay.append(relay_id)

                # 4d. DB row updates — captured here so step 5 (config
                # build) reads them.
                ch.exit_inbound_remote_id = exit_id
                ch.relay_inbound_remote_id = relay_id
                ch.exit_uuid = bootstrap_uuid
                ch.exit_pbk = exit_pbk
                ch.exit_pvk = exit_pvk
                ch.exit_sid = exit_sid
                ch.relay_pbk = relay_pbk
                ch.relay_pvk = relay_pvk
                ch.relay_sid = relay_sid
                session.add(ch)
            await session.commit()
            # Same expire-on-commit gotcha as above — step 5 reads
            # chain.id, ch.exit_port, ch.relay_port, ch.exit_uuid, etc.
            await session.refresh(chain)
            for row in channel_rows:
                await session.refresh(row)

            # Step 4e — open the chain inbound ports in UFW. Without
            # this, SYNs from clients (relay) and from the relay's
            # chain outbound (exit) get silently dropped by the
            # default-deny ufw policy on a fresh VPS.
            exit_ports_open = [ch.exit_port for ch in channel_rows]
            relay_ports_open = [ch.relay_port for ch in channel_rows]
            await _ufw_chain_ports(exit_srv, exit_ports_open, action="allow")
            await _ufw_chain_ports(relay_srv, relay_ports_open, action="allow")

            # Step 5 — push xrayTemplateConfig to the relay. We
            # rebuild a COMBINED template covering every chain bound
            # to this relay (including the one we just inserted into
            # the DB at step 3) — the panel stores one template per
            # panel, so a single-chain push would wipe routes for any
            # other chains sharing the same relay.
            template = await build_combined_relay_template(
                session=session,
                relay_xui_server_id=chain.relay_xui_server_id,
            )
            await _push_xray_template(
                relay_client=relay_client, template=template,
            )

            # Step 6 — restart Xray on the relay.
            await _restart_xray(relay_client)

    except Exception as exc:  # noqa: BLE001
        # Rollback panel-side state. Best-effort: a failed delete
        # here just means the operator has stranded inbounds they
        # can clean up via the panel UI — we'd rather raise the
        # original create error than mask it with a rollback error.
        logger.warning(
            "Chain create failed for chain id=%s, rolling back %s exit + %s relay inbounds: %s",
            chain.id, len(created_exit), len(created_relay), exc,
        )
        await _rollback_inbounds(
            exit_url=exit_url, exit_token=exit_token,
            relay_url=relay_url, relay_token=relay_token,
            exit_ids=created_exit, relay_ids=created_relay,
        )
        chain.status = "failed"
        chain.last_error = f"{type(exc).__name__}: {str(exc)[:900]}"
        chain.updated_at = datetime.now(timezone.utc)
        session.add(chain)
        await session.commit()
        raise

    # Step 7 — finalise.
    chain.status = "deployed"
    chain.last_error = None
    chain.last_synced_at = datetime.now(timezone.utc)
    chain.updated_at = chain.last_synced_at
    session.add(chain)
    await session.commit()
    await session.refresh(chain)
    return chain


async def _rollback_inbounds(
    *,
    exit_url: str, exit_token: str,
    relay_url: str, relay_token: str,
    exit_ids: List[int], relay_ids: List[int],
) -> None:
    """Best-effort `del_inbound` for every (panel, id) we created
    before the failure. Errors here are logged but not raised — the
    caller's exception is the actionable one."""
    if exit_ids:
        try:
            async with XuiClient(
                base_url=exit_url, api_token=exit_token, verify_tls=False,
            ) as c:
                for rid in exit_ids:
                    try:
                        await c.del_inbound(rid)
                    except Exception as e:  # noqa: BLE001
                        logger.warning(
                            "rollback: del_inbound %s on exit panel failed: %s",
                            rid, e,
                        )
        except Exception as e:  # noqa: BLE001
            logger.warning("rollback: exit panel unreachable for cleanup: %s", e)
    if relay_ids:
        try:
            async with XuiClient(
                base_url=relay_url, api_token=relay_token, verify_tls=False,
            ) as c:
                for rid in relay_ids:
                    try:
                        await c.del_inbound(rid)
                    except Exception as e:  # noqa: BLE001
                        logger.warning(
                            "rollback: del_inbound %s on relay panel failed: %s",
                            rid, e,
                        )
        except Exception as e:  # noqa: BLE001
            logger.warning("rollback: relay panel unreachable for cleanup: %s", e)


