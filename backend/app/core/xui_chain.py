async def orchestrate_add_client(
    *,
    chain: ProxyChain,
    channels: List[ChainChannel],
    label: Optional[str],
    session: AsyncSession,
) -> ChainClient:
    """Add a client to every relay-side inbound at once.

    The user gets back a `ChainClient` row with N
    `ChainClientChannel` children — one panel-side client UUID per
    channel. Each can be independently exported to a Node later.

    Rollback: if addClient on channel K of N fails, we delClient on
    channels 0..K-1 to keep the user/channel cardinality in lock-step
    (otherwise /sync would report N-1 hand-added clients next time).
    """
    _no_expire_on_commit(session)
    relay_xs = await session.get(XuiServer, chain.relay_xui_server_id)
    if relay_xs is None:
        raise RuntimeError(f"relay panel id={chain.relay_xui_server_id} missing")
    relay_srv = await session.get(Server, relay_xs.server_id)
    if relay_srv is None:
        raise RuntimeError(f"Server id={relay_xs.server_id} missing")

    effective_label = label or f"pi-{secrets.token_hex(4)}"

    chain_client = ChainClient(
        chain_id=chain.id,
        label=effective_label,
    )
    session.add(chain_client)
    await session.flush()

    relay_url = _api_base_url(relay_xs, relay_srv)
    added: List[tuple[int, str]] = []   # (inbound_remote_id, uuid) for rollback

    try:
        async with XuiClient(
            base_url=relay_url, api_token=relay_xs.api_token, verify_tls=False,
        ) as c:
            for ch in channels:
                uuid = await c.get_new_uuid()
                # v3.1.0: email is globally unique on ClientRecord
                # (uniqueIndex). Same `effective_label` across N
                # channels would collide on the 2nd add_client call.
                # Suffix with the channel's stable name so each
                # panel-side client is distinct ("alice-vk", "alice-mx",
                # ...). The UI groups them logically by prefix, and
                # PiTun's ChainClient → ChainClientChannel mapping
                # still owns the per-channel UUID for Node export.
                client_obj = {
                    "id": uuid,
                    "flow": "xtls-rprx-vision",
                    "email": f"{effective_label}-{ch.name}",
                    "limitIp": 0, "totalGB": 0, "expiryTime": 0,
                    "enable": True, "tgId": "", "subId": "",
                }
                await c.add_client(ch.relay_inbound_remote_id, client_obj)
                added.append((ch.relay_inbound_remote_id, uuid))

                cc = ChainClientChannel(
                    chain_client_id=chain_client.id,
                    channel_id=ch.id,
                    client_uuid=uuid,
                )
                session.add(cc)
            # x-ui-pro persists the client to the panel DB but doesn't
            # automatically reload Xray's running config (the generated
            # /usr/local/x-ui/bin/config.json still has only the prior
            # clients). Without this restart, the new UUID returns a
            # silent Reality drop → "Offline" Node + zero-byte speed
            # tests. Bounce Xray to pick up the inbound update.
            await c.restart_xray()
    except Exception:
        # Rollback panel-side adds (best-effort).
        if added:
            try:
                async with XuiClient(
                    base_url=relay_url, api_token=relay_xs.api_token,
                    verify_tls=False,
                ) as c2:
                    for inbound_id, uuid in added:
                        try:
                            await c2.del_client(inbound_id, uuid)
                        except Exception as e:  # noqa: BLE001
                            logger.warning(
                                "rollback: del_client (%s,%s) failed: %s",
                                inbound_id, uuid, e,
                            )
            except Exception as e:  # noqa: BLE001
                logger.warning(
                    "rollback: relay panel unreachable during client cleanup: %s",
                    e,
                )
        # Drop the (partial) DB rows before re-raising.
        await session.rollback()
        raise

    await session.commit()
    await session.refresh(chain_client)
    return chain_client


async def orchestrate_delete_client(
    *,
    chain: ProxyChain,
    chain_client: ChainClient,
    pairs: List[ChainClientChannel],
    channels_by_id: Dict[int, ChainChannel],
    session: AsyncSession,
) -> None:
    """Remove every panel-side client this ChainClient maps to, drop
    any Nodes that were exported from its channels, then drop the DB
    row (which cascades the ClientChannel pairs).

    Cascade rationale: a ChainClientChannel may have an
    `exported_node_id` pointing at a `Node` row that the user
    created via "Export to Node". Without this cleanup, removing
    the chain client leaves orphan Node rows whose UUID no longer
    authenticates against the panel (panel-side client is gone),
    cluttering the Nodes page and making routing rules referencing
    them fail silently. Mirror of the cascade in
    `xui.py::delete_client` (line 1607+) for regular x-ui clients.
    """
    from app.models import Node
    _no_expire_on_commit(session)

    # Step 1: collect Nodes to delete BEFORE we drop ChainClientChannel
    # rows (FK cascade would lose the linkage otherwise).
    nodes_to_delete: list[Node] = []
    for pair in pairs:
        if pair.exported_node_id is None:
            continue
        node = await session.get(Node, pair.exported_node_id)
        if node is not None:
            nodes_to_delete.append(node)

    relay_xs = await session.get(XuiServer, chain.relay_xui_server_id)
    relay_srv = (
        await session.get(Server, relay_xs.server_id) if relay_xs else None
    )

    # Step 2: panel-side delete (best-effort — proceed to DB cleanup
    # even if the relay is unreachable).
    if relay_xs is not None and relay_srv is not None:
        try:
            async with XuiClient(
                base_url=_api_base_url(relay_xs, relay_srv),
                api_token=relay_xs.api_token, verify_tls=False,
            ) as c:
                for pair in pairs:
                    ch = channels_by_id.get(pair.channel_id)
                    if ch is None:
                        continue
                    try:
                        await c.del_client(
                            ch.relay_inbound_remote_id, pair.client_uuid,
                        )
                    except Exception as e:  # noqa: BLE001
                        logger.warning(
                            "delete client: panel del_client (%s,%s) failed: %s",
                            ch.relay_inbound_remote_id, pair.client_uuid, e,
                        )
                # Mirror orchestrate_add_client: x-ui-pro persists the
                # delete to the panel DB but doesn't reload Xray, so the
                # removed UUID would keep working until the next restart.
                try:
                    await c.restart_xray()
                except Exception as e:  # noqa: BLE001
                    logger.warning("delete client: restart_xray failed: %s", e)
        except Exception as e:  # noqa: BLE001
            logger.warning("delete client: relay panel unreachable: %s", e)

    # Step 3: cascade-delete exported Nodes + ChainClientChannel pairs
    # + the ChainClient row itself. The FK `ChainClientChannel ->
    # ChainClient` has no `ondelete="CASCADE"` declaration in the
    # migration, and SQLAlchemy doesn't infer ORM-level cascade from a
    # plain Field-with-foreign_key — so dropping the parent leaves the
    # child rows orphaned in the DB unless we delete them here too.
    # (Verified by `TestOrchestrateDeleteClient` regression test.)
    for node in nodes_to_delete:
        logger.info(
            "delete chain client %d (%s): also dropping exported Node %d (%s)",
            chain_client.id, chain_client.label, node.id, node.name,
        )
        await session.delete(node)
    for pair in pairs:
        await session.delete(pair)
    await session.delete(chain_client)
    await session.commit()
