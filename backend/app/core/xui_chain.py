"""Two-hop proxy chain orchestrator (since v1.3.0-beta.7).

Wires together an EU **exit** x-ui panel and a RU **relay** x-ui panel
to recreate the working setup-eu.sh + setup-relay.sh pattern from the
user's reference scripts. The orchestrator is the single code path
that knows how to:

  1. Create N exit-side inbounds (xhttp + Reality, masked under
     exit_sni) on the EU panel — one per channel.
  2. Create N relay-side inbounds (TCP + Reality, masked under
     channel.client_sni) on the RU panel.
  3. Stitch them together with an `xrayTemplateConfig` push to the
     relay panel: outbounds[chain-<channel>] mirror each exit-inbound,
     routing.rules pair `inboundTag=<relay-tag>` → `outboundTag=
     chain-<channel>`. After the push we restart Xray on the relay
     so the new template takes effect.

The orchestrator is **atomic-ish**: if step N fails, we delete every
inbound we created in steps 1..N-1 via the panel API before raising.
Real atomicity across two independent panels isn't achievable (the
exit-side creates land before the relay-side ones, and either panel
can flake mid-way), but rollback turns a partial failure into a
clean re-runnable state instead of stranded zombie inbounds.

Schema decisions documented inline:
  * Inbound `tag` is set explicitly to `chain-<chain_id>-<name>-{exit|
    relay}`. The panel doesn't auto-tag inbounds, and xray needs an
    exact-match tag for the routing rules. Setting it here keeps
    /sync (Phase 6 part 2) cheap — we can find our inbounds by tag
    without trusting the remote_id alone.
  * Reality keys are generated by the panel's `getNewX25519Cert`
    endpoint (per-side, per-channel). We pull both halves of each
    pair into the DB so re-pushing the xrayTemplateConfig after a
    panel restart doesn't need to round-trip the panel for them.
  * `xrayTemplateConfig` is the panel's own setting key for "config
    Xray uses on start". We POST it via `/panel/setting/update` — the
    same path 3x-ui's web UI uses for its `Xray Config` editor.
"""
